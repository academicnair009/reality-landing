"""Build every raster/vector asset the v2 home page needs into assets/v2/.

Run from anywhere:  python3 docs/design/2026-10-28-v2/src/build_assets.py
Needs Pillow + NumPy only. Inputs are real files already in the repo (or stashed
in src/sources/ with their provenance). Nothing is generated by a model.
"""
import os, shutil
import numpy as np
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
A = os.path.join(REPO, "assets")
OUT = os.path.join(A, "v2")
SRC = os.path.join(HERE, "sources")
CANON_MARK = os.environ.get("RIALITI_MARK", os.path.expanduser("~/claude_ws/reality/branding/rialiti-logo-vector.svg"))

def out(*p):
    path = os.path.join(OUT, *p)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    return path

def save_pair(im, base, w, q_webp=78, q_jpg=80):
    """Resize (never upscale) and save webp + jpg. Returns the two paths."""
    if im.width > w:
        im = im.resize((w, round(im.height * w / im.width)), Image.LANCZOS)
    im = im.convert("RGB")
    p1 = out(base + f"-{im.width}.webp"); im.save(p1, "WEBP", quality=q_webp, method=6)
    p2 = out(base + f"-{im.width}.jpg"); im.save(p2, "JPEG", quality=q_jpg, optimize=True, progressive=True)
    return p1, p2

# ---------------------------------------------------------------- hero
# The real Verified screen from the Play listing (record ra-e58e1b6d5bed4de9).
scr = Image.open(os.path.join(A, "play", "screens", "04-verified.png")).convert("RGB")
# 1. the capture itself (the photograph inside the app's frame): x 147..933, y 55..1103
cap = scr.crop((147, 55, 933, 1103))
for w in (786, 560):
    save_pair(cap, "hero/capture", w)

# 2. the Verified capture panel, with its real rounded corners made transparent
x0, y0, x1, y1, r = 56, 1149, 1023, 1709, 44
card = scr.crop((x0, y0, x1, y1)).convert("RGBA")
ss = 4
m = Image.new("L", (card.width * ss, card.height * ss), 0)
ImageDraw.Draw(m).rounded_rectangle((0, 0, card.width * ss - 1, card.height * ss - 1), r * ss, fill=255)
card.putalpha(m.resize(card.size, Image.LANCZOS))
for w in (967, 640):
    c = card if card.width <= w else card.resize((w, round(card.height * w / card.width)), Image.LANCZOS)
    c.save(out(f"hero/record-card-{c.width}.webp"), "WEBP", quality=90, method=6)
    c.save(out(f"hero/record-card-{c.width}.png"), "PNG", optimize=True)

# ---------------------------------------------------------------- problem pair
# Landscape crops around the car so the edit (decals, number, scuffs) is legible at 320 px wide.
real = cap  # identical crop to the ad's car-verified-capture.jpg (786x1048)
edited = Image.open(os.path.join(SRC, "car-edited-by-hand.jpg")).convert("RGB")
assert edited.size == (785, 1046)
box = (0, 330, 785, 800)  # 785x470, car centred
shutil.rmtree(os.path.join(OUT, "problem"), ignore_errors=True)
for w in (785, 400):
    save_pair(real.crop(box), "problem/car-real", w)
    save_pair(edited.crop(box), "problem/car-edited", w)

# ---------------------------------------------------------------- proof
chk = Image.open(os.path.join(SRC, "check-record-ra-e58e1b6d5bed4de9-2026-10-28-390w@2x.png")).convert("RGB")
crop = chk.crop((28, 1192, 752, 2330))  # result card: T1 ring through the device line
crop.save(out("proof/check-record-724.png"), "PNG", optimize=True)
crop.save(out("proof/check-record-724.webp"), "WEBP", quality=86, method=6)
crop.resize((362, round(crop.height * 362 / crop.width)), Image.LANCZOS).save(out("proof/check-record-362.webp"), "WEBP", quality=86, method=6)

# ---------------------------------------------------------------- story (3 kept beats)
b1 = Image.open(os.path.join(SRC, "beat1-first-steps.jpg"))
b5 = Image.open(os.path.join(SRC, "beat5-turn.jpg"))
assert b1.size == b5.size, "turn must share the first-steps framing for the crossfade"
save_pair(b1, "story/first-steps", 681, q_webp=74, q_jpg=75)
save_pair(b5, "story/turn", 681, q_webp=74, q_jpg=75)
bm = Image.open(os.path.join(SRC, "beat7-bluemarble.jpg"))
for w in (1200, 760):
    save_pair(bm, "story/blue-marble", w, q_webp=72, q_jpg=70)

# ---------------------------------------------------------------- icons
shutil.copyfile(CANON_MARK, out("icons", "rialiti-mark.svg"))  # byte-identical canonical mark
ICONS = {
    "check.svg": '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M3.2 8.4l3 3 6.6-6.8" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round"/></svg>\n',
    "cross.svg": '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M4.2 4.2l7.6 7.6M11.8 4.2l-7.6 7.6" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"/></svg>\n',
}
for name, svg in ICONS.items():
    with open(out("icons", name), "w") as f:
        f.write(svg)

if __name__ == "__main__":
    for root, _, files in sorted(os.walk(OUT)):
        for fn in sorted(files):
            p = os.path.join(root, fn)
            if fn.endswith((".webp", ".jpg", ".png")):
                im = Image.open(p)
                print(f"{os.path.relpath(p, REPO):60s} {im.width}x{im.height}  {os.path.getsize(p)/1024:.0f} KB")
